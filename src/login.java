private final java.awt.Image bgOriginal = new javax.swing.ImageIcon(
        getClass().getResource("/images/login background.PNG")).getImage();
private int lastW = -1, lastH = -1;

// your designer put the background at y = -60, so design coords are shifted by 60
private static final int DESIGN_Y_SHIFT = 60;

private void place(javax.swing.JComponent c, int dx, int dy, int w,
                   int ox, int oy, double s) {
    java.awt.Dimension p = c.getPreferredSize();
    int cw = (w > 0) ? (int) (w * s) : p.width;
    c.setBounds(ox + (int) (dx * s),
                oy + (int) ((dy + DESIGN_Y_SHIFT) * s),
                cw, p.height);
}

private void scaleBackground() {
    int width = getContentPane().getWidth();
    int height = getContentPane().getHeight();
    if (width <= 0 || height <= 0) return;

    int imgW = bgOriginal.getWidth(null);
    int imgH = bgOriginal.getHeight(null);

    double s = Math.max((double) width / imgW, (double) height / imgH);
    int sw = (int) (imgW * s);
    int sh = (int) (imgH * s);
    int x = (width - sw) / 2;
    int y = (height - sh) / 2;

    // only rescale the image when its size actually changed (SCALE_SMOOTH is slow)
    if (sw != lastW || sh != lastH) {
        jLabel3.setIcon(new javax.swing.ImageIcon(
                bgOriginal.getScaledInstance(sw, sh, java.awt.Image.SCALE_SMOOTH)));
        lastW = sw;
        lastH = sh;
    }
    jLabel3.setBounds(x, y, sw, sh);

    // original designer coordinates, now scaled with the background
    place(jButton1,        390, 130, 0,   x, y, s);
    place(jLabel1,         790, 230, 0,   x, y, s);
    place(jLabel2,         730, 280, 269, x, y, s);
    place(jTextField1,     730, 310, 304, x, y, s);
    place(jPasswordField1, 730, 350, 304, x, y, s);
    place(jButton2,        730, 400, 0,   x, y, s);
    place(jCheckBox1,      830, 410, 0,   x, y, s);
}
