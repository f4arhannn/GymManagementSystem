    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        // Get details from the form
    String name = jTextField1.getText().trim();
    String mobile = jTextField2.getText().trim();
    String email = jTextField3.getText().trim();
    String father = jTextField4.getText().trim();
    String mother = jTextField5.getText().trim();
    String aadhaar = jTextField6.getText().trim();
    String ageText = jTextField7.getText().trim();
    String amountText = jTextField8.getText().trim();

    // Check for empty fields
    if (name.isEmpty() || mobile.isEmpty() || email.isEmpty()
            || father.isEmpty() || mother.isEmpty()
            || aadhaar.isEmpty() || ageText.isEmpty()
            || amountText.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Please fill in all fields.");
        return;
    }

    // Validate mobile number
    if (!mobile.matches("\\d{10}")) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Enter a valid 10-digit mobile number.");
        return;
    }

    // Validate email
    if (!email.matches(
            "[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}")) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Enter a valid email address.");
        return;
    }

    // Validate Aadhaar number
    if (!aadhaar.matches("\\d{12}")) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Aadhaar number must contain 12 digits.");
        return;
    }

    try {
        // Validate age and amount
        int age = Integer.parseInt(ageText);
        double amount = Double.parseDouble(amountText);

        if (age <= 0 || age > 120) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Enter a valid age.");
            return;
        }

        if (!Double.isFinite(amount) || amount <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Enter a valid amount greater than zero.");
            return;
        }

        // Get dropdown values
        String gender = jComboBox1.getSelectedItem().toString();
        String gymTime = jComboBox2.getSelectedItem().toString();

        // Create Member object
        Member member = new Member(
                name,
                mobile,
                email,
                father,
                mother,
                aadhaar,
                age,
                amount,
                gender,
                gymTime
        );

        // Save member details to MySQL
        String sql = "INSERT INTO members "
                + "(name, phone, email, father_name, mother_name, "
                + "aadhaar, age, amount_per_month, gender, gym_time) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, member.getName());
            pst.setString(2, member.getMobile());
            pst.setString(3, member.getEmail());
            pst.setString(4, member.getFather());
            pst.setString(5, member.getMother());
            pst.setString(6, member.getAadhaar());
            pst.setInt(7, member.getAge());
            pst.setDouble(8, member.getAmount());
            pst.setString(9, member.getGender());
            pst.setString(10, member.getGymTime());

            int rowsInserted = pst.executeUpdate();

            if (rowsInserted > 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Member registered successfully!");

                // Clear the fields after successful saving
                jTextField1.setText("");
                jTextField2.setText("");
                jTextField3.setText("");
                jTextField4.setText("");
                jTextField5.setText("");
                jTextField6.setText("");
                jTextField7.setText("");
                jTextField8.setText("");
            }
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Age and amount must be numeric.");

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error saving member: " + e.getMessage());
        e.printStackTrace();
    }
       
  

    }//GEN-LAST:event_jButton2ActionPerformed

